/**
 * Host half of the Extension Console bundle.
 *
 * The Extensions view is a second look at the profile's plugins: the unit a
 * person thinks of as "an extension" is a bundle — an installable package with
 * its own patch — rather than one Loader row. This half owns that view's
 * facts:
 *
 * - the unit registry: every bundle plus every built-in row no bundle owns,
 *   each with its rows, its problems, and its effective enablement;
 * - the dependency graph: module-level edges read from each mounted
 *   package's own manifest, projected onto units, with cycles reported;
 * - the mutations: enabling or disabling a whole unit, and retrying a failed
 *   one by restarting its rows.
 *
 * The browser half reads the facts over one exact HTTP route, because a
 * plugin cannot add a typed Remote namespace of its own: the Remote
 * contribution contract is generated by the DSH build, and a third-party
 * bundle has no way to produce one.
 */

import { existsSync, readFileSync, statSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

/** Services this plugin needs; without a managed profile there is nothing to show. */
export const inject = ['loader', 'pluginManager', 'profileContext', 'webServer', 'connection']

/** The exact route the browser half reads and writes. */
export const ROUTE = '/extensions-console'

/**
 * Apply the plugin.
 * @param ctx - the Host plugin context.
 */
export function apply(ctx) {
  const service = new ExtensionConsole(ctx)
  ctx.provide('extensionConsole', service)
  ctx.effect(() => ctx.webServer.register({
    kind: 'exact',
    path: ROUTE,
    handler: (req, res) => service.handle(req, res),
  }), 'extension-console: route')
}

/**
 * The Extension Console's Host service.
 */
class ExtensionConsole {
  /**
   * @param ctx - the Host plugin context.
   */
  constructor(ctx) {
    this.ctx = ctx
    this.manager = ctx.pluginManager
    /** One package manifest per mounted module, kept until the file changes. */
    this.manifests = new Map()
  }

  /**
   * Read the units alone: the bundles and the built-in rows they do not own.
   * @returns {Promise<Array<object>>} the units.
   */
  async units() {
    const [bundles, plugins] = await Promise.all([
      this.manager.listBundles(),
      this.manager.listPlugins(),
    ])
    return buildUnits(bundles, plugins)
  }

  /**
   * Read the whole view: units, edges, and cycles.
   * @returns {Promise<object>} the snapshot the browser renders.
   */
  async snapshot() {
    const [bundles, plugins] = await Promise.all([
      this.manager.listBundles(),
      this.manager.listPlugins(),
    ])
    const units = buildUnits(bundles, plugins)
    const modules = moduleEdges(this.ctx, plugins, this.manifests)
    const edges = projectEdges(modules, units)
    const cycles = findCycles(edges)
    for (const unit of units) {
      unit.dependencies = edges.filter((edge) => edge.from === unit.id).map((edge) => edge.to)
      unit.dependents = edges.filter((edge) => edge.to === unit.id).map((edge) => edge.from)
    }
    return {
      generatedAt: new Date().toISOString(),
      units,
      edges,
      cycles,
      moduleEdges: modules,
    }
  }

  /**
   * Enable or disable one unit as a whole.
   * @param {string} id - the unit id.
   * @param {boolean} enabled - the requested state.
   * @returns {Promise<object>} the manager's change result.
   */
  async setEnabled(id, enabled) {
    const unit = (await this.units()).find((item) => item.id === id)
    if (unit === undefined) throw new Error(`extension-console: no such extension ${JSON.stringify(id)}`)
    if (unit.readOnlyReason !== undefined) {
      throw new Error(`extension-console: ${unit.readOnlyReason}`)
    }
    if (unit.kind === 'bundle') {
      return this.manager.setBundleEnabled(unit.name, enabled)
    }
    const results = []
    for (const row of unit.rows) {
      results.push(await this.manager.setPluginEnabled(row.entryId, enabled))
    }
    return results[results.length - 1]
  }

  /**
   * Retry a failed extension by restarting the rows that failed.
   *
   * A row that failed to load stays failed while its options are unchanged,
   * so the restart is a disable followed by an enable: both are recorded in
   * the profile patch, and the enable brings the row back. A bundle whose
   * own patch failed has no failed row, so the bundle itself is restarted.
   * @param {string} id - the unit id.
   * @returns {Promise<object>} the manager's change result.
   */
  async retry(id) {
    const unit = (await this.units()).find((item) => item.id === id)
    if (unit === undefined) throw new Error(`extension-console: no such extension ${JSON.stringify(id)}`)
    if (unit.readOnlyReason !== undefined) {
      throw new Error(`extension-console: ${unit.readOnlyReason}`)
    }
    const failed = unit.rows.filter((row) => row.phase === 'failed')
    if (failed.length > 0) {
      let last
      for (const row of failed) {
        await this.manager.setPluginEnabled(row.entryId, false)
        last = await this.manager.setPluginEnabled(row.entryId, true)
      }
      return last
    }
    if (unit.kind === 'bundle') {
      await this.manager.setBundleEnabled(unit.name, false)
      return this.manager.setBundleEnabled(unit.name, true)
    }
    let last
    for (const row of unit.rows) {
      await this.manager.setPluginEnabled(row.entryId, false)
      last = await this.manager.setPluginEnabled(row.entryId, true)
    }
    return last
  }

  /**
   * Answer one HTTP request.
   * @param {object} req - the Node request.
   * @param {object} res - the Node response.
   * @returns {Promise<void>} after the response is written.
   */
  async handle(req, res) {
    // The route carries the profile's plugin facts, so it answers only to a
    // browser the Connection has already admitted; Connection owns the 401.
    if (!this.ctx.connection.authorizeIndex(req, res)) return
    try {
      if (req.method === 'POST') {
        const body = JSON.parse((await readBody(req)) || '{}')
        const result = body.action === 'retry'
          ? await this.retry(String(body.id))
          : await this.setEnabled(String(body.id), Boolean(body.enabled))
        json(res, 200, { ok: true, result })
        return
      }
      json(res, 200, await this.snapshot())
    } catch (error) {
      json(res, 400, { ok: false, error: error instanceof Error ? error.message : String(error) })
    }
  }
}

/**
 * Write a JSON response.
 * @param {object} res - the Node response.
 * @param {number} status - the HTTP status.
 * @param {unknown} payload - the body.
 */
function json(res, status, payload) {
  const body = JSON.stringify(payload)
  res.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'content-length': Buffer.byteLength(body),
    'cache-control': 'no-store',
  })
  res.end(body)
}

/**
 * Read a request body as text.
 * @param {object} req - the Node request.
 * @returns {Promise<string>} the body.
 */
function readBody(req) {
  return new Promise((resolve, reject) => {
    let text = ''
    req.setEncoding?.('utf8')
    req.on('data', (chunk) => {
      text += chunk
      if (text.length > 1_000_000) reject(new Error('extension-console: request body too large'))
    })
    req.on('end', () => resolve(text))
    req.on('error', reject)
  })
}

/**
 * Build the unit registry: every bundle, plus every built-in row no bundle
 * owns grouped by its package.
 * @param {Array<object>} bundles - the manager's bundles.
 * @param {Array<object>} plugins - the manager's plugin rows.
 * @returns {Array<object>} the units.
 */
function buildUnits(bundles, plugins) {
  const units = []
  const owned = new Set()
  for (const bundle of bundles) {
    const rows = []
    for (const row of bundle.rows ?? []) {
      if (row.entryId === undefined) continue
      owned.add(row.entryId)
      const live = plugins.find((item) => item.entryId === row.entryId)
      rows.push(rowView(row, live))
    }
    units.push({
      id: `bundle:${bundle.name}`,
      kind: 'bundle',
      name: bundle.name,
      title: bundle.meta?.title ?? bundle.name,
      description: bundle.description ?? bundle.meta?.description ?? '',
      icon: bundle.meta?.icon,
      diagnostics: bundle.meta?.diagnostics,
      version: bundle.version,
      enabled: bundle.enabled === true,
      installed: bundle.installed === true,
      official: bundle.official === true,
      optional: bundle.optional === true,
      removable: bundle.removable === true,
      source: bundle.source,
      readOnlyReason: bundle.readOnlyReason,
      problems: [
        ...(bundle.error === undefined ? [] : [{
          code: bundle.error.code ?? 'bundle-error',
          severity: 'error',
          message: bundle.error.message ?? bundle.error.code ?? 'the bundle could not be loaded',
        }]),
        ...diagnosticProblems(bundle.meta?.diagnostics),
      ],
      rows,
      dependencies: [],
      dependents: [],
    })
  }
  const builtIn = new Map()
  for (const plugin of plugins) {
    if (owned.has(plugin.entryId)) continue
    if (plugin.readOnlyReason === 'management-required') continue
    const name = plugin.moduleName
    const group = builtIn.get(name) ?? { name, rows: [], enabled: true }
    group.rows.push(rowView({ rowId: plugin.entryId, moduleName: name }, plugin))
    builtIn.set(name, group)
  }
  for (const group of builtIn.values()) {
    const failed = group.rows.filter((row) => row.phase === 'failed')
    units.push({
      id: `built-in:${group.name}`,
      kind: 'built-in',
      name: group.name,
      title: group.rows[0]?.meta?.title ?? group.name,
      description: group.rows[0]?.meta?.description ?? '',
      icon: group.rows[0]?.meta?.icon,
      version: undefined,
      enabled: group.rows.every((row) => row.enabled),
      installed: true,
      official: true,
      optional: false,
      removable: false,
      source: undefined,
      readOnlyReason: group.rows.find((row) => row.readOnlyReason !== undefined)?.readOnlyReason,
      problems: [
        ...failed.map((row) => ({
          code: 'load-failed',
          severity: 'error',
          message: `the plugin row ${row.entryId} failed to load`,
        })),
        ...diagnosticProblems(group.rows[0]?.meta?.diagnostics),
      ],
      rows: group.rows,
      dependencies: [],
      dependents: [],
    })
  }
  units.sort((a, b) => String(a.title).localeCompare(String(b.title)))
  return units
}

/**
 * Turn a package's metadata diagnostics into problems.
 * @param {unknown} diagnostics - the diagnostics the package reported.
 * @returns {Array<object>} the problems.
 */
function diagnosticProblems(diagnostics) {
  if (!Array.isArray(diagnostics)) return []
  return diagnostics.map((diagnostic) => ({
    code: diagnostic?.code ?? 'metadata-diagnostic',
    severity: 'warning',
    message: diagnostic?.message ?? diagnostic?.code ?? 'the package reported a metadata diagnostic',
  }))
}

/**
 * Describe one Loader row.
 * @param {object} row - the bundle's row.
 * @param {object} live - the live plugin entry, when there is one.
 * @returns {object} the row view.
 */
function rowView(row, live) {
  return {
    entryId: row.entryId,
    rowId: row.rowId,
    moduleName: row.moduleName,
    enabled: live?.enabled ?? true,
    phase: live?.fiberPhase ?? null,
    readOnlyReason: live?.readOnlyReason,
    meta: live?.meta ?? row.meta,
  }
}

/**
 * Read the module-level dependency edges of every mounted row.
 *
 * The edge source is each package's own manifest: `dependencies`,
 * `peerDependencies`, and `optionalDependencies` name the packages it needs.
 * @param {object} ctx - the Host plugin context.
 * @param {Array<object>} plugins - the manager's plugin rows.
 * @returns {Array<object>} the edges, one per dependent module and dependency.
 */
function moduleEdges(ctx, plugins, cache) {
  const edges = []
  for (const plugin of plugins) {
    const manifest = manifestFor(ctx, plugin.moduleName, cache)
    if (manifest === undefined) continue
    const names = new Set([
      ...Object.keys(manifest.dependencies ?? {}),
      ...Object.keys(manifest.peerDependencies ?? {}),
      ...Object.keys(manifest.optionalDependencies ?? {}),
    ])
    for (const name of names) {
      edges.push({ from: plugin.moduleName, to: name })
    }
  }
  return edges
}

/**
 * Read one mounted module's own package manifest.
 *
 * The Loader's base URL is a resolution anchor, not the module's file, so the
 * module is resolved from the profile first and from the installation second.
 * The answer is kept until the manifest file changes.
 * @param {object} ctx - the Host plugin context.
 * @param {string} moduleName - the module specifier.
 * @param {Map<string, object>} cache - the answers already read.
 * @returns {object|undefined} the manifest, when it is readable.
 */
function manifestFor(ctx, moduleName, cache) {
  const profile = ctx.profileContext
  const anchors = [profile?.dir, profile?.installAnchor].filter((value) => typeof value === 'string')
  let found
  for (const anchor of anchors) {
    try {
      const resolved = createRequire(join(anchor, 'package.json')).resolve(moduleName)
      found = manifestAbove(resolved)
      if (found !== undefined) break
    } catch {
      // The next anchor may know this module.
    }
  }
  if (found === undefined) {
    cache.delete(moduleName)
    return undefined
  }
  const cached = cache.get(moduleName)
  if (cached !== undefined && cached.path === found.path && cached.mtimeMs === found.mtimeMs) {
    return cached.manifest
  }
  cache.set(moduleName, found)
  return found.manifest
}

/**
 * Read the package manifest that owns a resolved module file.
 * @param {string} filePath - the resolved module file.
 * @returns {object|undefined} the manifest and its file facts, when readable.
 */
function manifestAbove(filePath) {
  let dir = dirname(filePath)
  for (let depth = 0; depth < 8; depth += 1) {
    const candidate = join(dir, 'package.json')
    if (existsSync(candidate)) {
      try {
        const stat = statSync(candidate)
        return {
          path: candidate,
          mtimeMs: stat.mtimeMs,
          manifest: JSON.parse(readFileSync(candidate, 'utf8')),
        }
      } catch {
        return undefined
      }
    }
    const next = dirname(dir)
    if (next === dir) break
    dir = next
  }
  return undefined
}

/**
 * Project module-level edges onto units.
 *
 * A module belongs to the bundle that declares it as a row; a bundle's own
 * package name belongs to that bundle even when another bundle also declares
 * a row for it.
 * @param {Array<object>} modules - the module edges.
 * @param {Array<object>} units - the units.
 * @returns {Array<object>} the unit edges.
 */
function projectEdges(modules, units) {
  const owner = new Map()
  for (const unit of units) owner.set(unit.name, unit.id)
  for (const unit of units) {
    for (const row of unit.rows) {
      if (!owner.has(row.moduleName)) owner.set(row.moduleName, unit.id)
    }
  }
  const seen = new Set()
  const edges = []
  for (const edge of modules) {
    const from = owner.get(edge.from)
    const to = owner.get(edge.to)
    if (from === undefined || to === undefined || from === to) continue
    const key = `${from}\u0000${to}`
    if (seen.has(key)) continue
    seen.add(key)
    edges.push({ from, to, kind: 'package' })
  }
  return edges
}

/**
 * Find the cycles of a unit graph.
 * @param {Array<object>} edges - the unit edges.
 * @returns {Array<Array<string>>} one entry per cycle, each a list of unit ids.
 */
function findCycles(edges) {
  const adjacency = new Map()
  for (const edge of edges) {
    const list = adjacency.get(edge.from) ?? []
    list.push(edge.to)
    adjacency.set(edge.from, list)
  }
  const cycles = []
  const seen = new Set()
  const stack = []
  const onStack = new Set()
  const visit = (node) => {
    stack.push(node)
    onStack.add(node)
    for (const next of adjacency.get(node) ?? []) {
      if (onStack.has(next)) {
        const cycle = stack.slice(stack.indexOf(next))
        const key = [...cycle].sort().join('\u0000')
        if (!seen.has(key)) {
          seen.add(key)
          cycles.push(cycle)
        }
      } else if (!stack.includes(next)) {
        visit(next)
      }
    }
    stack.pop()
    onStack.delete(node)
  }
  for (const node of adjacency.keys()) visit(node)
  return cycles
}

