#!/usr/bin/env node
/*---------------------------------------------------------------------------------------------
 *  DSH S1 spike — derive type-correct EMPTY return values for the NotSupported stub actors.
 *
 *  WHY: a blanket `return undefined` stub is NOT safe. The vendored extension host does e.g.
 *
 *      this._proxy.$getTools().then(tools => { for (const tool of tools) { ... } });
 *
 *  so a `undefined` reply crashes the extension host with "tools is not iterable".
 *  Every MainThread method must answer with a value of the right shape.
 *
 *  This script parses `extHost.protocol.ts` (the single source of truth for the protocol) and
 *  emits `spike/src/stub-returns.ts`:
 *      channel.method -> [] | 0 | false | '' | undefined
 *
 *  Usage: node gen-stub-returns.mjs
 *--------------------------------------------------------------------------------------------*/

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const PROTOCOL = resolve(ROOT, 'upstream/src/vs/workbench/api/common/extHost.protocol.ts');

const src = readFileSync(PROTOCOL, 'utf8');

/** Find `export interface MainThread<X>Shape ... { ... }` blocks. */
const shapeRe = /export interface (MainThread\w*Shape)[^{]*\{([\s\S]*?)\n\}/g;

/** Map the proxy identifier constant -> its shape interface. */
const ctxRe = /(\w+):\s*createProxyIdentifier<(\w+)>\('([^']+)'\)/g;

const ctxToShape = new Map();
let m;
while ((m = ctxRe.exec(src))) {
	ctxToShape.set(m[1], m[2]);
}

function defaultFor(returnType) {
	if (!returnType) { return 'undefined'; }
	let t = returnType.replace(/\s+/g, ' ').trim();
	// unwrap Promise<...>
	const pm = /^Promise<([\s\S]*)>$/.exec(t);
	if (pm) { t = pm[1].trim(); }
	// unwrap Dto<...> / SerializableObjectWithBuffers<...>
	const dm = /^(?:Dto|SerializableObjectWithBuffers)<([\s\S]*)>$/.exec(t);
	if (dm) { t = dm[1].trim(); }
	if (/\[\]$/.test(t)) { return '[]'; }               // Foo[]  /  Promise<Foo[]>
	if (/^(void|Promise<void>|undefined|Promise<undefined>)$/.test(t)) { return 'undefined'; }
	if (/^(number|Promise<number>)$/.test(t)) { return '0'; }
	if (/^(boolean|Promise<boolean>)$/.test(t)) { return 'false'; }
	if (/^(string|Promise<string>)$/.test(t)) { return "''"; }
	return 'undefined';
}

const out = {};
let shapeCount = 0;
shapeRe.lastIndex = 0;
while ((m = shapeRe.exec(src))) {
	const shapeName = m[1];
	const body = m[2];
	shapeCount++;
	// find the channel constant that uses this shape
	let channel = null;
	for (const [ctx, shape] of ctxToShape) {
		if (shape === shapeName) { channel = ctx; break; }
	}
	if (!channel) { continue; }
	// method signatures: $name(...): ReturnType;
	const methodRe = /\$([A-Za-z0-9_]+)\s*\(([^)]*)\)\s*:\s*([^;]+);/g;
	let mm;
	while ((mm = methodRe.exec(body))) {
		const method = mm[1];
		const ret = mm[3];
		out[`${channel}.$${method}`] = defaultFor(ret);
	}
}

const entries = Object.entries(out).sort(([a], [b]) => a.localeCompare(b));
const ts = `/*---------------------------------------------------------------------------------------------
 *  GENERATED by spike/gen-stub-returns.mjs — do not edit by hand.
 *  Source: upstream/src/vs/workbench/api/common/extHost.protocol.ts (commit ${process.env.VSCODE_COMMIT ?? 'unknown'})
 *
 *  Type-correct EMPTY return value for every MainThread* RPC method, derived from the protocol.
 *  A stub must answer with the right SHAPE (e.g. [] for a list) or the extension host crashes.
 *--------------------------------------------------------------------------------------------*/

export const STUB_RETURNS: Record<string, any> = {
${entries.map(([k, v]) => `\t'${k}': ${v},`).join('\n')}
};
`;

const outPath = resolve(ROOT, 'spike/src/stub-returns.ts');
writeFileSync(outPath, ts);
console.log(`[gen-stub-returns] parsed ${shapeCount} MainThread shapes, wrote ${entries.length} method defaults -> ${outPath}`);
